#!/usr/bin/env bash
# Generates the site-identity values file (top-level key `site:` ONLY) for one site.
# Usage: generate-site-identity.sh <config-values.yaml> <primary|dr> <out.yaml>
# application and environment come from the config path (<app>/<env>/values.yaml) and are
# cross-checked against the file contents. Requires: bash, yq (mikefarah v4).
set -euo pipefail
die() { echo "ERROR: $*" >&2; exit 1; }
[[ $# -eq 3 ]] || die "usage: $0 <config-values.yaml> <primary|dr> <out.yaml>"
command -v yq >/dev/null || die "yq (mikefarah v4) not found in PATH"
cfg=$1; role=$2; out=$3
[[ -f $cfg ]] || die "config not found: $cfg"
env=$(basename "$(dirname "$cfg")")
app=$(basename "$(dirname "$(dirname "$cfg")")")
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
reg=$here/../environments/registry.yaml
domain=${CLUSTER_DOMAIN:-cluster.local}

[[ $app =~ ^[a-z][a-z0-9]{1,15}$ ]] || die "invalid application folder name: $app"
[[ $env =~ ^[a-z]+$ ]]              || die "invalid environment folder name: $env"
case $role in primary) partner_role=dr ;; dr) partner_role=primary ;; *) die "site must be primary or dr" ;; esac

envcode=$(yq ".environments.\"$env\"" "$reg")
[[ $envcode =~ ^[0-9]+$ ]] || die "environment '$env' is not in environments/registry.yaml"
sitecode()    { yq ".sites.\"$1\"" "$reg"; }
[[ $(yq '.application.name' "$cfg") == "$app" && $(yq '.application.environment' "$cfg") == "$env" ]] \
  || die "config declares a different application/environment than its path ($app/$env)"
count=$(yq '.gemfire.cluster.locatorCount' "$cfg")
[[ $count =~ ^[1-9][0-9]*$ ]] || die "gemfire.cluster.locatorCount missing or invalid"
port=$(yq '.ports.locator' "$reg")

me=$app-$env-$role; partner=$app-$env-$partner_role
my_id=$(( envcode * 10 + $(sitecode "$role") ))
partner_id=$(( envcode * 10 + $(sitecode "$partner_role") ))

# Primary and DR share the config file, hence the same locatorCount, so the partner's
# locator list can be derived without asking the partner.
locators() {  # <release>
  local i; for ((i = 0; i < count; i++)); do echo "$1-locator-$i.$1-locator-hl.$1.svc.$domain[$port]"; done
}
list() { locators "$1" | sed 's/^/    - /'; }

mkdir -p "$(dirname "$out")"
cat > "$out" <<YAML
# GENERATED by scripts/generate-site-identity.sh. Site identity only; do not edit.
site:
  name: $me
  role: $role
  distributedSystemId: $my_id
  clusterDomain: $domain
  locators:
$(list "$me")
  partner:
    name: $partner
    namespace: $partner
    distributedSystemId: $partner_id
    locators:
$(list "$partner" | sed 's/^/  /')
  tls:
    issuerName: gemfire-$env-ca
    secretName: $me-tls
    passwordSecretName: $me-tls-password
  credentialsSecretName: $me-credentials
YAML
yq '.' "$out" >/dev/null || die "generated file is not valid YAML"
echo "wrote $out ($me, ds-id $my_id, partner $partner ds-id $partner_id)"
